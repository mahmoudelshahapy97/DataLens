"""Instructions in the control plane, against a real database.

Rules used to be markdown files named after a slug of their own text, and two
bugs followed from that naming rather than from anything anybody wrote:

* two rules sharing their first sixty characters resolved to the same filename,
  so adding the second silently destroyed the first;
* editing a rule's wording moved it to a new filename and left the old file in
  place, so the rule appeared twice and the stale copy kept reaching the prompt.

Both are pinned in :class:`TestTheBugsThatMotivatedTheMove`, parametrised across
the markdown and Postgres stores, and both were checked to fail against the
unfixed markdown store rather than merely assumed to. The markdown store is still
shipped -- it is the demo-mode fallback and the library's default -- so it had to
be fixed, not abandoned.

The rest is what moving to a database is *for*: an id that survives an edit,
isolation enforced by a column rather than by a directory, pack bookkeeping that
can be a transaction, and rows that disappear when the workspace does.
"""

from __future__ import annotations

from types import SimpleNamespace

import pytest

from vanna.capabilities.knowledge import (
    Instruction,
    InstructionOrigin,
    InstructionScope,
)

pytestmark = pytest.mark.integration


